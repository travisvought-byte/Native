// Draws the outline of every state and places each Nation's government office on it.
// Output: data/map/us.json, which scripts/build.py turns into the map on the home page.
// Run with `npm run map` after data/nations.json changes. Needs the three dev dependencies in package.json.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
import { geoAlbersUsa, geoPath } from 'd3-geo';
import { feature } from 'topojson-client';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const read = (p) => JSON.parse(readFileSync(join(root, p), 'utf8'));

// us-atlas ships state shapes already projected to a 975 x 610 box with this projection,
// so the same projection puts points in the right place on those shapes.
const WIDTH = 975, HEIGHT = 610;
const projection = geoAlbersUsa().scale(1300).translate([WIDTH / 2, HEIGHT / 2]);
const topo = read('node_modules/us-atlas/states-albers-10m.json');
const states = feature(topo, topo.objects.states).features;

const FIPS = { '01': 'AL', '02': 'AK', '04': 'AZ', '05': 'AR', '06': 'CA', '08': 'CO', '09': 'CT', '10': 'DE', '11': 'DC',
  '12': 'FL', '13': 'GA', '15': 'HI', '16': 'ID', '17': 'IL', '18': 'IN', '19': 'IA', '20': 'KS', '21': 'KY', '22': 'LA',
  '23': 'ME', '24': 'MD', '25': 'MA', '26': 'MI', '27': 'MN', '28': 'MS', '29': 'MO', '30': 'MT', '31': 'NE', '32': 'NV',
  '33': 'NH', '34': 'NJ', '35': 'NM', '36': 'NY', '37': 'NC', '38': 'ND', '39': 'OH', '40': 'OK', '41': 'OR', '42': 'PA',
  '44': 'RI', '45': 'SC', '46': 'SD', '47': 'TN', '48': 'TX', '49': 'UT', '50': 'VT', '51': 'VA', '53': 'WA', '54': 'WV',
  '55': 'WI', '56': 'WY' };

// Whole-pixel coordinates keep the page small; at this size the difference cannot be seen.
const path = geoPath().digits(0);
const shapes = [];
for (const s of states) {
  const code = FIPS[String(s.id).padStart(2, '0')];
  if (!code) continue; // territories are not on this map yet
  const [cx, cy] = path.centroid(s).map(Math.round);
  shapes.push({ code, name: s.properties.name, d: path(s), cx, cy });
}
shapes.sort((a, b) => a.name.localeCompare(b.name));

const nations = read('data/nations.json').nations;
const points = [];
let off = 0;
for (const n of nations) {
  const p = projection([n.lon, n.lat]);
  if (!p) { off++; continue; }
  points.push({ id: n.id, x: Math.round(p[0] * 10) / 10, y: Math.round(p[1] * 10) / 10 });
}

mkdirSync(join(root, 'data/map'), { recursive: true });
writeFileSync(join(root, 'data/map/us.json'), JSON.stringify({
  note: 'Generated by scripts/build_map.mjs from us-atlas (U.S. Census Bureau shapes) and data/nations.json. Do not edit by hand.',
  width: WIDTH, height: HEIGHT, states: shapes, points,
}) + '\n');
console.log(`${shapes.length} state shapes, ${points.length} offices placed, ${off} outside the map frame`);
